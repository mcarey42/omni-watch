static unsigned clz32(uint32_t x)
{
    unsigned n = 0;
    if (!(x & 0xffff0000u)) { n += 16; x <<= 16; }
    if (!(x & 0xff000000u)) { n += 8; x <<= 8; }
    if (!(x & 0xf0000000u)) { n += 4; x <<= 4; }
    if (!(x & 0xc0000000u)) { n += 2; x <<= 2; }
    if (!(x & 0x80000000u)) n += 1;
    return n;
}

uint32_t omni_recip_q16(uint32_t x)
{
    if (x < 32768u) return x ? 0xffffffffu : 0;   /* outside the domain: saturate */
    const unsigned n = clz32(x);                    /* x = m / 2^n, m in [2^31, 2^32): mf = m / 2^32 in [0.5, 1) */
    const uint32_t m = x << n;
    uint32_t r = RECIP[(m >> 23) & 255];            /* ~ 1/mf in Q30 */
    const uint32_t e = (uint32_t)(((uint64_t)m * r) >> 32);   /* mf * r in Q30: about 2^30 */
    r = (uint32_t)(((uint64_t)r * ((2u << 30) - e)) >> 30);   /* Newton: r (2 - mf r) */
    /* 2^32 / x = (1 / mf) 2^n = r 2^(n - 30); n <= 16 in the domain */
    return r >> (30 - n);
}

float omni_atan2_tab(float y, float x)
{
    const float ax = x < 0 ? -x : x, ay = y < 0 ? -y : y;
    const int swap = ay > ax;
    const float hi = swap ? ay : ax, lo = swap ? ax : ay;
    if (hi == 0) return 0;
    if (!(hi >= 1.0f / 65536 && hi < 256.0f && lo == lo)) return atan2f(y, x);   /* outside the domain, or NaN: libm */
    /* lo / hi by the reciprocal, hi in Q16 and lo in Q24, both scaled first so that hi is in [0.5, 1) (Q16 [32768,
     * 65536)): there the reciprocal keeps 17 significant bits (1/200 in Q16 would be 327). lo <= hi, so lo stays below
     * 2^24 after the scaling, and the ratio comes out in Q24. */
    uint32_t hq = (uint32_t)(hi * 65536.0f), lq = (uint32_t)(lo * 16777216.0f);
    const unsigned n = clz32(hq);
    if (n > 16) {
        hq <<= n - 16;
        lq <<= n - 16;
    } else {
        hq >>= 16 - n;
        lq >>= 16 - n;
    }
    uint32_t q = (uint32_t)(((uint64_t)lq * omni_recip_q16(hq)) >> 16);   /* lo / hi in Q24 */
    if (q > (1u << 24)) q = 1u << 24;
    const unsigned i = q >> 14, f = q & 16383;
    float a = ATAN[i];
    if (i < 1024) a += (ATAN[i + 1] - ATAN[i]) * ((float)f * (1.0f / 16384));
    if (swap) a = 1.57079632679489662f - a;
    if (x < 0) a = 3.14159265358979324f - a;
    return y < 0 ? -a : a;
}
