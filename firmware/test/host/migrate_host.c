/* migrate_host: a theme's boot-time migration (omni/migrate.h) over migrate_host's line format (kv_mem.h), for
 * tools/nvs_fixture.py and test_nvs_image. A host tool, not a test.
 *
 *   migrate_host --in <kv.txt> --out <kv.txt> --theme <omni|dw> [--fail-after N] [--force]
 *       The Omni runs local, then shared (spec §6); the dw stub runs shared only. Lines the migration does not set
 *       pass through byte-unchanged. --fail-after N: every set after the Nth returns ERR. --force: force = true for
 *       both parts. Prints each part's result; exits 0 when it ran (FAILED included), 2 on a usage or file error.
 *   migrate_host --emit-fixture <dir>
 *       Writes the golden fixture's value files (settings.hex, clockcal.hex, batrec.hex, shared_v2.hex) from the
 *       Stage 3 encoders, once (`nvs_fixture.py make`, preflight C4): they are committed and never regenerated by
 *       `check`, which pins settings.hex against a hand-written byte table instead. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "kv_mem.h"
#include "omni/batrec.h"
#include "omni/cities.h"
#include "omni/clockcal.h"
#include "omni/migrate.h"
#include "omni/settings.h"
#include "omni/shared.h"

/* The Omni's limits as Task 5's descriptor declares them: 8 faces, 3 reveals (flip default), the default order. */
static const uint8_t k_omni_def[] = { 0, 1, 2, 3, 4, 5, 6, 7 };
static const omni_theme_limits_t k_omni_lim = { 8, 3, 0, sizeof k_omni_def, k_omni_def };

static const char *mig_name(omni_mig_t r)
{
    switch (r) {
    case OMNI_MIG_NOT_NEEDED: return "NOT_NEEDED";
    case OMNI_MIG_NO_SOURCE: return "NO_SOURCE";
    case OMNI_MIG_DONE: return "DONE";
    case OMNI_MIG_FAILED: return "FAILED";
    }
    return "?";
}

static int write_hex(const char *dir, const char *name, const uint8_t *b, size_t n)
{
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", dir, name);
    FILE *f = fopen(path, "w");
    if (f == NULL) { perror(path); return -1; }
    for (size_t i = 0; i < n; i++) fprintf(f, "%02x", b[i]);
    fputc('\n', f);
    if (fclose(f) != 0) { perror(path); return -1; }
    return 0;
}

static int emit_fixture(const char *dir)
{
    /* omni/settings: the sample values, v2 */
    omni_settings_t s;
    omni_settings_defaults(&s);
    s.city = (uint16_t)omni_city_find_key("Columbus", "US");
    s.brightness = 45; s.sleep_s = 15; s.h24 = false; s.sound_on = true; s.volume = 30;
    s.reduced_motion = false; s.reveal_style = OMNI_REVEAL_FLIP;
    const uint8_t car[] = { 0, 1, 2, 3, 7 };
    memset(s.carousel, 0, sizeof s.carousel);
    memcpy(s.carousel, car, sizeof car);
    s.carousel_len = sizeof car;
    uint8_t sb[OMNI_SETTINGS_BLOB_SIZE];
    omni_settings_encode(&s, sb);

    /* omni/clockcal: a valid v1 blob, rate 12 ppm, 3 log entries */
    omni_clk_saved_t ck;
    memset(&ck, 0, sizeof ck);   /* the padding too: the blob is a raw memcpy of the struct */
    ck.rate_ppm = 12;
    ck.interval_s = 3600;
    ck.n_est = 3;
    ck.log_n = 3;
    ck.log_head = 3;
    for (int i = 0; i < 3; i++) {
        ck.log[i].unix_s = 1793000000 + 3600 * i;
        ck.log[i].step_ms = 40 - 10 * i;
        ck.log[i].applied_ms = 5 * i;
        ck.log[i].uptime_s = 7200u + 3600u * (uint32_t)i;
        ck.log[i].since_s = i ? 3600u : 0u;
        ck.log[i].asleep_s = i ? 3000u : 0u;
        ck.log[i].rate_ppm = 10 + i;
    }
    ck.log[2].rate_ppm = 12;
    omni_clockcal_t chk;
    if (!omni_clk_restore(&chk, &ck)) { fprintf(stderr, "clockcal fixture out of range\n"); return -1; }
    uint8_t cb[OMNI_CLK_BLOB_SIZE];
    const uint16_t cver = OMNI_CLK_BLOB_VERSION;
    memcpy(cb, &cver, sizeof cver);
    memcpy(cb + sizeof cver, &ck, sizeof ck);

    /* omni/batrec: a valid v2 blob, one completed session */
    omni_batrec_t r;
    omni_batrec_init(&r);
    omni_batrec_boot(&r, true, omni_batrec_snap(&r, 1793000000, 10, 100, 4180));
    omni_batrec_vbus(&r, false, omni_batrec_snap(&r, 1793000600, 610, 98, 4150));
    for (int i = 0; i < 12; i++) omni_batrec_wake(&r, i % 3 ? WAKE_LIFT : WAKE_TOUCH);
    omni_batrec_wake(&r, WAKE_GLANCE);
    omni_batrec_vbus(&r, true, omni_batrec_snap(&r, 1793036600, 36610, 71, 3880));
    uint8_t bb[OMNI_BATREC_BLOB_SIZE];
    omni_batrec_encode(&r, bb);
    omni_batrec_t rchk;
    if (!omni_batrec_decode(&rchk, bb, sizeof bb)) { fprintf(stderr, "batrec fixture invalid\n"); return -1; }

    /* watch/shared written by a newer build: version 2, 50 B (the v1 layout, brightness 80, a 4-byte tail) */
    omni_shared_t sh;
    omni_shared_defaults(&sh);
    sh.city = s.city;
    sh.brightness = 80;
    sh.tail_len = 4;
    const uint8_t tail[] = { 0xde, 0xad, 0xbe, 0xef };
    memcpy(sh.tail, tail, sizeof tail);
    uint8_t vb[OMNI_REC_MAX];
    size_t vn = omni_shared_encode(&sh, vb, sizeof vb);
    vb[0] = 2;

    if (write_hex(dir, "settings.hex", sb, sizeof sb) || write_hex(dir, "clockcal.hex", cb, sizeof cb) ||
        write_hex(dir, "batrec.hex", bb, sizeof bb) || write_hex(dir, "shared_v2.hex", vb, vn))
        return -1;
    return 0;
}

static int usage(void)
{
    fprintf(stderr, "usage: migrate_host --in <kv.txt> --out <kv.txt> --theme <omni|dw> [--fail-after N] [--force]\n"
                    "       migrate_host --emit-fixture <dir>\n");
    return 2;
}

int main(int argc, char **argv)
{
    const char *in = NULL, *out = NULL, *theme = NULL, *emit = NULL;
    int fail_after = -1;
    bool force = false;
    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        bool more = i + 1 < argc;
        if (strcmp(a, "--in") == 0 && more) in = argv[++i];
        else if (strcmp(a, "--out") == 0 && more) out = argv[++i];
        else if (strcmp(a, "--theme") == 0 && more) theme = argv[++i];
        else if (strcmp(a, "--emit-fixture") == 0 && more) emit = argv[++i];
        else if (strcmp(a, "--fail-after") == 0 && more) {
            char *end;
            long v = strtol(argv[++i], &end, 10);
            if (*end != '\0' || v < 0 || v > 1000) return usage();
            fail_after = (int)v;
        } else if (strcmp(a, "--force") == 0) force = true;
        else return usage();
    }
    if (emit != NULL) return in || out || theme ? usage() : (emit_fixture(emit) == 0 ? 0 : 2);
    if (in == NULL || out == NULL || theme == NULL) return usage();
    bool omni = strcmp(theme, "omni") == 0;
    if (!omni && strcmp(theme, "dw") != 0) return usage();

    static kv_mem_t m;
    kv_mem_init(&m);
    FILE *f = fopen(in, "r");
    if (f == NULL) { perror(in); return 2; }
    int rc = kv_mem_load_lines(&m, f);
    fclose(f);
    if (rc != 0) { kv_mem_free(&m); return 2; }

    m.fail_after = fail_after;
    omni_kv_t kv = kv_mem_iface(&m);
    if (omni) printf("local %s\n", mig_name(omni_migrate_omni_local(&kv, &k_omni_lim, force)));
    printf("shared %s\n", mig_name(omni_migrate_shared(&kv, theme, force)));
    printf("sets %d ok %d omni-refused %d\n", m.sets, m.sets_ok, m.old_ns_sets);

    f = fopen(out, "w");
    if (f == NULL) { perror(out); kv_mem_free(&m); return 2; }
    rc = kv_mem_save_lines(&m, f);
    if (fclose(f) != 0) rc = -1;
    kv_mem_free(&m);
    if (rc != 0) { fprintf(stderr, "%s: write failed\n", out); return 2; }
    return 0;
}
