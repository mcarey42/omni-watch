/* ---- the oracle's entry points (not of the copy) */
static cu_t oracle_ctx;   /* host only: the tests run on one thread */

void rd_cu_steam_oracle(uint32_t T, float amt, bool red, uint16_t *fb, int stride, omni_rect_t clip)
{
    const cu_state_t s = {T, amt, red};
    oracle_ctx.blob.a = STEAM_BLOB;
    oracle_ctx.blob.w = oracle_ctx.blob.h = BLOB;
    steam_draw(&oracle_ctx, &s, fb, stride, clip);
}

/* the copy's inner-loop count over the whole of RD_CU_STEAM: every (puff, pixel) whose bilinear sample it works out
 * (the loop bounds and the two range tests of steam_draw, nothing drawn) */
unsigned long rd_cu_steam_oracle_samples(uint32_t T, float amt)
{
    const cu_state_t s = {T, amt, false};
    const omni_rect_t r = RD_CU_STEAM;
    const unsigned np = puffs_of(&s, oracle_ctx.puff);
    unsigned long n = 0;
    for (int y = r.y0; y < r.y1; y++)
        for (unsigned i = 0; i < np; i++) {
            const puff_t *p = &oracle_ctx.puff[i];
            if (y < p->iy0 || y >= p->iy1) continue;
            const float vy = ((float)y + 0.5f - p->y0) * p->inv - 0.5f;
            if (!(vy > -1.f && vy < (float)BLOB)) continue;
            const int ix0 = ifl(p->x0), ix1 = icl(p->x0 + (float)BLOB / p->inv);
            const int xa = ix0 > r.x0 ? ix0 : r.x0, xb = ix1 < r.x1 ? ix1 : r.x1;
            for (int x = xa; x < xb; x++) {
                const float ux = ((float)x + 0.5f - p->x0) * p->inv - 0.5f;
                n += ux > -1.f && ux < (float)BLOB;
            }
        }
    return n;
}
